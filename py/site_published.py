"""Write docs/published.md: one table per product listing every dataset and
the URL of each published form.

Run by Quarto before rendering the site (project pre-render in
docs/_quarto.yml). Reads products/*/product.json and datasets.tsv only; no
network access. A product without "public_base" in product.json is listed
without URLs.
"""

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "published.md"

# form label, path under <public_base>/<dataset>/
FORMS = [
    ("mdim VRT", "mdim.vrt"),
    ("kerchunk", "kerchunk/"),
    ("Icechunk", "icechunk/"),
    ("flat refs", "flat/"),
    ("STAC", "stac/collection.json"),
]


def rows(tsv):
    with open(tsv, newline="") as f:
        lines = [ln for ln in f if ln.strip() and not ln.startswith("#")]
    return list(csv.DictReader(lines, delimiter="\t"))


def main():
    out = [
        "---",
        'title: "Published datasets"',
        "---",
        "",
        "<!-- generated by py/site_published.py from products/*/; do not edit -->",
        "",
        "Datasets as listed in `products/*/datasets.tsv`;",
        "`catalog.sh products/<product> config/source-coop.sh check` confirms",
        "that each one is published. All forms of a dataset are rendered from",
        "one byte-reference store and read the same source files; which",
        "readers open which form is on the",
        "[Readers](readers.qmd) page, and worked reads are under",
        "[Examples](examples/index.qmd).",
        "",
    ]
    for pj in sorted(ROOT.glob("products/*/product.json")):
        prod = json.loads(pj.read_text())
        base = prod.get("public_base", "").rstrip("/")
        out += [f"## {prod.get('title', prod['id'])}", "", prod.get("description", ""), ""]
        if base:
            out += [f"Base: `{base}/<dataset>/`", ""]
        head = "| Dataset | Title |" + "".join(f" {f} |" for f, _ in FORMS)
        out += [head, "|---|---|" + "---|" * len(FORMS)]
        for r in rows(pj.parent / "datasets.tsv"):
            ds = r["dataset"]
            cells = "".join(f" [{f}]({base}/{ds}/{p}) |" if base else " |" for f, p in FORMS)
            out.append(f"| `{ds}` | {r['title']} |{cells}")
        out.append("")
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
